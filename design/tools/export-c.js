// Dumps the renderer's fixed data (palette, both bitmap fonts) as C tables for
// the firmware: firmware/src/screen/bs_tables.h. The wall textures, light maps
// and vignette are generated at boot by the C port itself (bs_init_tables), so
// they live in fast internal RAM instead of being fetched through the flash cache.
//
//   node tools/export-c.js            (run from design/)
const fs = require('fs');
const path = require('path');
const B = require('../babel-screen.js');

const OUT = path.join(__dirname, '..', '..', 'firmware', 'src', 'screen', 'bs_tables.h');

// Glyph order: printable ASCII 32..126, then the extras at 0x80.. in the C strings.
const EXTRAS = ['·', '…', '␣', '▮', '×'];
const ORDER = [];
for (let c = 32; c < 127; c++) ORDER.push(String.fromCharCode(c));
ORDER.push(...EXTRAS);

function rows(src, ch, w, n) {
  const s = src[ch];
  const out = new Array(n).fill(0);
  if (!s) return null;
  s.split('|').forEach((row, r) => {
    let m = 0;
    for (let i = 0; i < w; i++) if (row[i] === '#') m |= 1 << (w - 1 - i);
    out[r] = m;
  });
  return out;
}

const lines = [];
lines.push('// Generated by design/tools/export-c.js from design/babel-screen.js. Do not edit.');
lines.push('#pragma once');
lines.push('#include <stdint.h>');
lines.push('');
lines.push('// Extra glyphs, addressed by these byte codes in strings.');
lines.push('#define BS_CH_MIDDOT   "\\x80"');
lines.push('#define BS_CH_ELLIPSIS "\\x81"');
lines.push('#define BS_CH_VSPACE   "\\x82"');
lines.push('#define BS_CH_BLOCK    "\\x83"');
lines.push('#define BS_CH_TIMES    "\\x84"');
lines.push(`#define BS_GLYPHS ${ORDER.length}`);
lines.push('');
lines.push('// 16-colour palette, RGB565 (native order; swap bytes for the SPI panel).');
lines.push('static const uint16_t BS_PALETTE565[16] = {');
for (const p of B.PALETTE) lines.push(`  0x${p.rgb565.toString(16).toUpperCase().padStart(4, '0')}, // ${p.index.toString().padStart(2)} ${p.name.padEnd(8)} ${p.css}`);
lines.push('};');
lines.push('');
lines.push('// 5x7 body font on a 6x9 cell, 8 rows (row 7 holds descenders), bit 4 = left column.');
lines.push('static const uint8_t BS_FONT5[BS_GLYPHS][8] = {');
const q5 = rows(B.FONT5_SRC, '?', 5, 8);
for (const ch of ORDER) {
  const r = rows(B.FONT5_SRC, ch, 5, 8) || q5;
  lines.push(`  {${r.join(',')}}, // ${JSON.stringify(ch)}`);
}
lines.push('};');
lines.push('');
lines.push('// 3x5 micro font, upper case only (lower case maps to upper), bit 2 = left column.');
lines.push('static const uint8_t BS_FONT3[BS_GLYPHS][5] = {');
const q3 = rows(B.FONT3_SRC, '?', 3, 5);
for (const ch of ORDER) {
  const r = rows(B.FONT3_SRC, ch.toUpperCase(), 3, 5) || q3;
  lines.push(`  {${r.join(',')}}, // ${JSON.stringify(ch)}`);
}
lines.push('};');
lines.push('');

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, lines.join('\n'));
console.log('wrote', path.relative(process.cwd(), OUT));
